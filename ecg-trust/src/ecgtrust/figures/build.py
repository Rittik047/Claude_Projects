"""Run every figure group and write an index of what was produced."""

from __future__ import annotations

from pathlib import Path

from ecgtrust.config import Config
from ecgtrust.figures import GROUPS


def build_figures(cfg: Config, only=None) -> dict[str, list[Path]]:
    from ecgtrust.figures import analysis, data, explain

    groups = set(only or GROUPS)
    root = cfg.reports / "figures"
    made: dict[str, list[Path]] = {}
    if "01_data" in groups:
        made["01_data"] = data.make(cfg, root / "01_data")
    made.update(analysis.make(cfg, root, groups))
    if "07_explainability" in groups:
        made["07_explainability"] = explain.make(cfg, root / "07_explainability")
    _index(root)
    return made


def _index(root: Path) -> None:
    lines = ["# Figures", "", "Generated by `ecgtrust figures`.", ""]
    for g in GROUPS:
        files = sorted((root / g).rglob("*.png")) if (root / g).exists() else []
        if files:
            lines += [f"## {g}", ""]
            lines += [f"- [{f.relative_to(root / g)}]({f.relative_to(root)})" for f in files]
            lines.append("")
    root.mkdir(parents=True, exist_ok=True)
    (root / "README.md").write_text("\n".join(lines))
